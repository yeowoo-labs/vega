static bool in(const Range *ranges, size_t count, uint32_t codepoint) {
    size_t low = 0, high = count;
    while (low < high) {
        size_t middle = (low + high) / 2;
        if (codepoint < ranges[middle].first) high = middle;
        else if (codepoint > ranges[middle].last) low = middle + 1;
        else return true;
    }
    return false;
}

unsigned vega_width(uint32_t codepoint) {
    if (in(zero, sizeof(zero) / sizeof(*zero), codepoint)) return 0;
    return in(wide, sizeof(wide) / sizeof(*wide), codepoint) ? 2 : 1;
}

uint32_t vega_visible(uint32_t codepoint) {
    if (codepoint < 0x20) return 0x2400 + codepoint;
    if (codepoint == 0x7F) return 0x2421;
    if (codepoint >= 0x80 && codepoint < 0xA0) return 0xFFFD;
    return codepoint;
}

size_t vega_decode(const char *text, size_t length, size_t at, uint32_t *codepoint) {
    const unsigned char *p = (const unsigned char *)text + at;
    size_t left = length - at, need = p[0] < 0x80 ? 1 : p[0] < 0xE0 ? 2 : p[0] < 0xF0 ? 3 : 4;
    if (need > left) { *codepoint = 0xFFFD; return left; }
    uint32_t value = need == 1 ? p[0] : need == 2 ? p[0] & 0x1Fu : need == 3 ? p[0] & 0x0Fu : p[0] & 0x07u;
    for (size_t i = 1; i < need; ++i) value = value << 6 | (p[i] & 0x3Fu);
    *codepoint = value;
    return need;
}

unsigned vega_text_width(const char *text, size_t length) {
    unsigned width = 0;
    for (size_t at = 0; at < length;) {
        uint32_t codepoint;
        at += vega_decode(text, length, at, &codepoint);
        width += vega_width(vega_visible(codepoint));
    }
    return width;
}
